// geminiBlockReader 阻塞读取直到 Close：模拟上游无任何分片（空闲超时）。
type geminiBlockReader struct {
	mu     sync.Mutex
	closed bool
}

func (r *geminiBlockReader) Read(p []byte) (int, error) {
	for {
		r.mu.Lock()
		if r.closed {
			r.mu.Unlock()
			return 0, io.EOF
		}
		r.mu.Unlock()
		time.Sleep(5 * time.Millisecond)
	}
}

func (r *geminiBlockReader) Close() error {
	r.mu.Lock()
	r.closed = true
	r.mu.Unlock()
	return nil
}

// 零分片 + 异常结束（空闲超时）：上游通常已收到请求并计费，至少按 prompt 估算收，
// 并标记消费日志；这是 stream-vs-nonstream §12.3 策略 A 的兜底。
func TestGeminiStreamHandlerAbnormalZeroChunkChargesPromptEstimate(t *testing.T) {
	oldTimeout := constant.StreamingTimeout
	constant.StreamingTimeout = 1
	t.Cleanup(func() { constant.StreamingTimeout = oldTimeout })

	c, _ := gin.CreateTestContext(httptest.NewRecorder())
	c.Request = httptest.NewRequest(http.MethodPost, "/v1/chat/completions", nil)

	info := &relaycommon.RelayInfo{
		OriginModelName: "gemini-3-flash-preview",
		DisablePing:     true,
		ChannelMeta:     &relaycommon.ChannelMeta{UpstreamModelName: "gemini-3-flash-preview"},
	}
	info.SetEstimatePromptTokens(123)

	usage, err := GeminiChatStreamHandler(c, info, &http.Response{Body: &geminiBlockReader{}})
	require.Nil(t, err)
	require.NotNil(t, usage)
	assert.Equal(t, 123, usage.PromptTokens)
	assert.Equal(t, 123, usage.TotalTokens)
	assert.True(t, info.AbnormalStreamSettled)
}

