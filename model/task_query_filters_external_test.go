package model

import (
	"os"
	"strings"
	"testing"

	"github.com/QuantumNous/new-api/common"
	"github.com/stretchr/testify/require"
	"gorm.io/driver/mysql"
	"gorm.io/driver/postgres"
	"gorm.io/gorm"
)

// TestTaskQueryFiltersConfiguredDatabases runs the same assertions as the
// SQLite test against real MySQL and PostgreSQL instances. The model filter
// uses dialect-specific JSON extraction, so all three engines must be proven.
func TestTaskQueryFiltersConfiguredDatabases(t *testing.T) {
	tests := []struct {
		name      string
		env       string
		dbType    common.DatabaseType
		dialector func(string) gorm.Dialector
	}{
		{"mysql", "TEST_MYSQL_DSN", common.DatabaseTypeMySQL, func(dsn string) gorm.Dialector { return mysql.Open(dsn) }},
		{"postgres", "TEST_POSTGRES_DSN", common.DatabaseTypePostgreSQL, func(dsn string) gorm.Dialector {
			return postgres.New(postgres.Config{DSN: dsn, PreferSimpleProtocol: true})
		}},
	}
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			dsn := strings.TrimSpace(os.Getenv(test.env))
			if dsn == "" {
				t.Skipf("%s is not configured", test.env)
			}
			db, err := gorm.Open(test.dialector(dsn), &gorm.Config{})
			require.NoError(t, err)
			sqlDB, err := db.DB()
			require.NoError(t, err)
			t.Cleanup(func() { _ = sqlDB.Close() })

			originalDB := DB
			originalMain, originalLog := common.MainDatabaseType(), common.LogDatabaseType()
			DB = db
			common.SetDatabaseTypes(test.dbType, test.dbType)
			initCol()
			t.Cleanup(func() {
				DB = originalDB
				common.SetDatabaseTypes(originalMain, originalLog)
				initCol()
			})
			require.NoError(t, db.AutoMigrate(&User{}, &Task{}))

			runTaskQueryFilterAssertions(t)
		})
	}
}
