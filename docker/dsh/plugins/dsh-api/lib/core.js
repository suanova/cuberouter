function mintId(prefix) {
  return prefix + '-' + Date.now().toString(36) + '-' + Math.random().toString(36).slice(2, 10)
}

function userMessage(text, source) {
  return {
    id: mintId('msg'),
    role: 'user',
    content: [{ type: 'text', text }],
    source: source || { kind: 'user' },
  }
}

// 注入指令的 producer-owned source。
// dsh ≥0.2.1（会话格式 v4）的准入校验拒绝「kind 为 plugin 的 v3 旧形态」（抛
// SessionFormatError: format v4 message requires a producer-owned source kind），
// v4 等价形态是「kind: 'plugin:<name>'」且不再携带 plugin 字段；0.1.x 无该校验，
// 新形态同样被接受。见 dsh-session-format-v3-to-v4 的 producerKind()。
const API_SOURCE = { kind: 'plugin:dsh-api', form: 'instructions' }

function textOf(message) {
  const blocks = message && message.content
  if (!Array.isArray(blocks)) return ''
  return blocks.filter((b) => b && b.type === 'text').map((b) => b.text || '').join('')
}

function readBody(req, limitBytes) {
  return new Promise((resolve, reject) => {
    const chunks = []
    let size = 0
    req.on('data', (chunk) => {
      size += chunk.length
      if (size > limitBytes) {
        reject(new Error('request body too large'))
        try { req.destroy() } catch { /* ignore */ }
        return
      }
      chunks.push(chunk)
    })
    req.on('end', () => {
      const buf = new Uint8Array(size)
      let off = 0
      for (const c of chunks) {
        buf.set(c, off)
        off += c.length
      }
      resolve(new TextDecoder('utf-8').decode(buf))
    })
    req.on('error', reject)
  })
}

function pathnameOf(url) {
  const q = url.indexOf('?')
  return q === -1 ? url : url.slice(0, q)
}

function isAbsolutePath(p) {
  if (typeof p !== 'string' || p.length === 0) return false
  return p.startsWith('/') || /^[a-zA-Z]:[\\/]/.test(p) || p.startsWith('\\\\')
}

// ---------------------------------------------------------------------------
// Artifacts — the files a turn produced.
//
// The vocabulary mirrors the Web UI's delivered-files row: the path comes from
// the arguments of a successful first-party mutation call (`write`, `edit`, a
// mutating `str_replace_editor`), never from the closing prose. A turn that
// writes its output through a shell command leaves no mutation call, so the
// cwd is also diffed against a snapshot taken when the turn opened; only names
// that appeared or changed during the turn join the list. Files created
// outside the cwd by shell commands stay outside both vocabularies.
// ---------------------------------------------------------------------------
const MAX_ARTIFACTS = 32

// cwd-diff candidates only: enough to catch a document or media output, narrow
// enough to skip caches, logs and editor scratch files.
const ARTIFACT_EXTENSIONS = new Set([
  'pptx', 'ppt', 'docx', 'doc', 'xlsx', 'xls', 'pdf',
  'md', 'html', 'htm', 'csv', 'json', 'txt', 'svg',
  'png', 'jpg', 'jpeg', 'gif', 'webp', 'mp4', 'webm', 'mp3', 'wav', 'zip',
])

const ARTIFACT_MIME_TYPES = {
  pptx: 'application/vnd.openxmlformats-officedocument.presentationml.presentation',
  ppt: 'application/vnd.ms-powerpoint',
  docx: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document',
  doc: 'application/msword',
  xlsx: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
  xls: 'application/vnd.ms-excel',
  pdf: 'application/pdf',
  md: 'text/markdown; charset=utf-8',
  html: 'text/html; charset=utf-8',
  htm: 'text/html; charset=utf-8',
  csv: 'text/csv; charset=utf-8',
  json: 'application/json; charset=utf-8',
  txt: 'text/plain; charset=utf-8',
  svg: 'image/svg+xml',
  png: 'image/png',
  jpg: 'image/jpeg',
  jpeg: 'image/jpeg',
  gif: 'image/gif',
  webp: 'image/webp',
  mp4: 'video/mp4',
  webm: 'video/webm',
  mp3: 'audio/mpeg',
  wav: 'audio/wav',
  zip: 'application/zip',
}

function basenameOf(path) {
  const parts = String(path || '').split(/[\\/]/)
  const name = parts[parts.length - 1] || ''
  return name || 'file'
}

function extensionOf(name) {
  const index = name.lastIndexOf('.')
  return index <= 0 ? '' : name.slice(index + 1).toLowerCase()
}

function isRecord(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

/** Extract the file path a supported mutation call writes, or null. */
function mutationPath(name, rawArguments) {
  let args
  if (typeof rawArguments === 'string') {
    try {
      args = JSON.parse(rawArguments)
    } catch {
      return null
    }
  } else {
    args = rawArguments
  }
  if (!isRecord(args)) return null
  const path = typeof args.file_path === 'string' && args.file_path.trim() !== ''
    ? args.file_path
    : typeof args.path === 'string' && args.path.trim() !== '' ? args.path : null
  if (path === null) return null
  switch (name) {
    case 'write':
      return typeof args.content === 'string' ? path : null
    case 'edit':
      return typeof args.old_string === 'string' && args.old_string !== ''
        && typeof args.new_string === 'string' && args.old_string !== args.new_string
        && (args.replace_all === undefined || typeof args.replace_all === 'boolean')
        ? path
        : null
    case 'str_replace_editor':
      switch (args.command) {
        case 'create':
          return typeof args.file_text === 'string' ? path : null
        case 'str_replace':
          return typeof args.old_str === 'string' && args.old_str !== ''
            && (args.new_str === undefined || typeof args.new_str === 'string')
            ? path
            : null
        case 'insert':
          return typeof args.insert_line === 'number' && Number.isInteger(args.insert_line)
            && args.insert_line >= 0 && typeof args.new_str === 'string'
            ? path
            : null
        default:
          return null
      }
    default:
      return null
  }
}

/** Stable artifact key: the display name, narrowed to the key alphabet. */
function artifactKey(name, used) {
  const base = String(name).replace(/[^A-Za-z0-9._~-]/g, '-').replace(/^[^A-Za-z0-9]+/, '').slice(0, 120) || 'file'
  let key = base
  for (let n = 2; used.has(key); n += 1) {
    const suffix = '-' + n
    key = base.slice(0, 120 - suffix.length) + suffix
  }
  used.add(key)
  return key
}

/** Direct-child file versions of a directory, or undefined when unreadable. */
async function snapshotCwd(fs, cwd) {
  if (!fs || !cwd) return undefined
  try {
    const entries = await fs.listDir(await fs.resolve(cwd, { cwd }))
    const snapshot = new Map()
    for (const entry of entries) snapshot.set(entry.name, entry.version)
    return snapshot
  } catch {
    return undefined
  }
}

/** Resolve, stat and keep the produced paths that still name a regular file. */
async function collectArtifacts(fs, cwd, produced, snapshot) {
  if (!fs) return []
  const paths = []
  const seen = new Set()
  const remember = (path) => {
    if (typeof path !== 'string' || path === '' || seen.has(path)) return
    seen.add(path)
    paths.push(path)
  }
  for (const path of produced || []) remember(path)
  if (snapshot) {
    try {
      const entries = await fs.listDir(await fs.resolve(cwd, { cwd }))
      for (const entry of entries) {
        if (entry.type !== 'file') continue
        if (!ARTIFACT_EXTENSIONS.has(extensionOf(entry.name))) continue
        const previous = snapshot.get(entry.name)
        if (previous !== undefined && entry.version !== undefined && previous === entry.version) continue
        remember(entry.target && entry.target.displayPath)
      }
    } catch { /* the cwd went away between snapshot and settle */ }
  }

  const artifacts = []
  const used = new Set()
  for (const path of paths) {
    if (artifacts.length >= MAX_ARTIFACTS) break
    let target
    let info
    try {
      target = await fs.resolve(path, { cwd })
      info = await fs.stat(target)
    } catch { /* unresolvable or outside this filesystem's reach */ }
    if (!info || info.type !== 'file' || !(info.size > 0)) continue
    const name = basenameOf(target.displayPath)
    const extension = extensionOf(name)
    artifacts.push({
      key: artifactKey(name, used),
      name,
      size: info.size,
      mimeType: ARTIFACT_MIME_TYPES[extension] || 'application/octet-stream',
      path: target.displayPath,
    })
  }
  return artifacts
}

/** The public artifact shape: what the file is, not where it lives. */
function publicArtifacts(task) {
  if (!Array.isArray(task.artifacts)) return []
  return task.artifacts.map((artifact) => ({
    key: artifact.key,
    name: artifact.name,
    size: artifact.size,
    mimeType: artifact.mimeType,
  }))
}

function contentDisposition(name) {
  const ascii = String(name).replace(/[^\x20-\x7e]/g, '_').replace(/["\\]/g, '_')
  return 'attachment; filename="' + ascii + '"; filename*=UTF-8\'\'' + encodeURIComponent(String(name))
}

// ---------------------------------------------------------------------------
// Task lifecycle
// ---------------------------------------------------------------------------
function summarize(events, firstSeq) {
  let started = false
  let reply = ''
  const transcript = []
  const toolCalls = []
  const produced = []
  const mutationCalls = new Map()
  let turnEnd
  for (const event of events) {
    if (event.seq < firstSeq) continue
    if (event.type === 'turn/start') { started = true; continue }
    if (!started) continue
    if (event.type === 'assistant/message') {
      const joined = textOf(event.data.message)
      if (joined !== '') {
        reply = joined
        transcript.push({ role: 'assistant', text: joined })
      }
    } else if (event.type === 'user/message' && event.data.source && event.data.source.kind === 'user') {
      const joined = textOf(event.data)
      if (joined !== '') transcript.push({ role: 'user', text: joined })
    } else if (event.type === 'tool/call') {
      toolCalls.push({ name: event.data.name, callId: event.data.callId })
      const path = mutationPath(event.data.name, event.data.arguments)
      if (path !== null) mutationCalls.set(String(event.data.callId), path)
    } else if (event.type === 'tool/result') {
      const message = event.data && event.data.message
      const blocks = message && Array.isArray(message.content) ? message.content : []
      if (!blocks[0] || blocks[0].isError === true) continue
      const path = mutationCalls.get(String((message.source || {}).callId))
      if (path !== undefined && !produced.includes(path)) produced.push(path)
    } else if (event.type === 'turn/end') {
      turnEnd = event.data.reason
    }
  }
  return { reply, transcript, toolCalls, produced, turnEnd }
}

/**
 * Drive one task to quiescence and store the outcome on the task record.
 * Never rejects: every failure lands on the task record.
 */
async function runTask(ctx, state, task) {
  const cfg = state.cfg
  const timer = ctx.get('timer') || { timeout: ctx.timeout }
  const finish = (patch) => {
    Object.assign(task, patch)
    task.finishedAt = Date.now()
    state.running = Math.max(0, state.running - 1)
    if (task._resolve) task._resolve(task)
  }

  state.running += 1
  let handle
  let timedOut = false

  try {
    const agents = ctx.get('agents')
    const sessions = ctx.get('sessions')
    const agentPresets = ctx.get('agentPresets')
    const agentDefaultModel = ctx.get('agentDefaultModel')
    if (!agents) {
      return finish({ status: 'failed', error: { code: 'NO_AGENTS', message: 'agents service unavailable' } })
    }

    // Resolve model selection + preset BEFORE creation (meta is snapshotted
    // before setup runs).
    const selection = agentDefaultModel ? agentDefaultModel.currentSelection() : undefined
    const provider = task.provider || (selection && selection.provider)
    const model = task.model || (selection && selection.model)
    const agentOptions = {}
    if (provider) agentOptions.provider = provider
    if (model) agentOptions.model = model
    if (task.maxTokens) agentOptions.maxTokens = task.maxTokens
    if (task.reasoningEffort) agentOptions.reasoningEffort = task.reasoningEffort

    // preset id 已在提交时（handleCreate）解析为 roster id；这里不再二次 resolve，
    // 避免每个任务重复全量扫描预设目录（agentPresets.resolve 是 unmemoized 的）。
    const resolvedPresetId = task.preset || undefined

    const selRef = { current: selection, assembled: undefined }
    const setup = async (agentCtx) => {
      installModelSelectionLocal(agentCtx, selRef)
      if (agentPresets && resolvedPresetId) await agentPresets.mount(agentCtx, resolvedPresetId)
    }

    // Reuse a live idle agent for continuations; otherwise create or resume.
    const live = task.continuation && state.handles.get(task.sessionId)
    if (live && live.agent.status === 'idle') {
      handle = live
      if (live.cleanup) { try { live.cleanup() } catch { /* ignore */ } live.cleanup = undefined }
    } else if (task.continuation) {
      handle = await agents.resume({ resumeSessionId: task.sessionId, agentOptions, setup })
    } else {
      handle = await agents.create({
        sessionId: task.sessionId,
        meta: {
          ...(task.cwd ? { cwd: task.cwd } : {}),
          ...(resolvedPresetId ? { agentPreset: resolvedPresetId } : {}),
        },
        agentOptions,
        setup,
      })
    }
    const agent = handle.agent
    state.handles.set(task.sessionId, { agent, handle, cleanup: undefined })

    // Timeout guard: cancel the agent when the budget expires.
    const timeoutMs = Math.min(Math.max(Number(task.timeoutMs) || cfg.defaultTimeoutMs, 1000), cfg.maxTimeoutMs)
    let firstSeq = 0
    let cwdSnapshot
    const timeoutDisposer = timer.timeout(() => {
      if (!timedOut && task.status === 'running' && state.handles.get(task.sessionId) === handle) {
        timedOut = true
        try { agent.cancel({ kind: 'user' }) } catch { /* ignore */ }
      }
    }, timeoutMs)

    try {
      // Creation quiescence, then open the turn.
      await agent.whenIdle()
      firstSeq = agent.session.seq
      // The artifact list is a diff against this snapshot, so it must be taken
      // before the turn can touch the cwd.
      cwdSnapshot = await snapshotCwd(ctx.get('fs'), task.cwd)
      // system 仅在会话首个任务注入：续接任务重复注入会在上下文里累积重复指令。
      if (task.system && !task.continuation) {
        agent.inject(userMessage(task.system, API_SOURCE))
      }
      agent.followup(userMessage(task.prompt))
      await agent.whenIdle()
    } finally {
      timeoutDisposer()
    }

    if (sessions) {
      try { await sessions.flush(agent.session) } catch { /* flush is best-effort */ }
    }

    // dsh 0.1.5-rc.1 的 Session 没有 `events` 属性（只有 snapshotEvents()/ownEvents()）；
    // 旧写法会让 summarize 抛 "events is not iterable"，任务一律记成 failed 且拿不到 reply。
    // snapshotEvents() 默认返回 [0, seq) 全量事件，与原来的语义一致（下面仍按 firstSeq 过滤）。
    const outcome = summarize(agent.session.snapshotEvents(), firstSeq)
    const turnKind = outcome.turnEnd ? outcome.turnEnd.kind : 'unknown'

    let status
    let error
    if (timedOut) {
      status = 'timeout'
    } else if (task._cancelRequested) {
      status = 'canceled'
    } else if (turnKind === 'completed') {
      status = 'completed'
    } else if (turnKind === 'max-tokens') {
      // 输出被上限截断：reply 保留已有部分文本，但不得报成功。
      status = 'max-tokens'
    } else if (turnKind === 'aborted') {
      // 非本 API 发起的取消（用户/父级/hook）——语义上是 canceled 而非 failed。
      status = 'canceled'
    } else if (turnKind === 'blocked') {
      status = 'failed'
      error = { code: 'BLOCKED', message: 'the turn ended blocked (a policy stopped the turn)' }
    } else if (turnKind === 'interrupted') {
      status = 'failed'
      error = { code: 'INTERRUPTED', message: 'the turn was interrupted (closed by crash recovery); re-run the task' }
    } else if (turnKind === 'error') {
      status = 'failed'
      const e = outcome.turnEnd.error || {}
      error = { code: e.code || 'LLM_ERROR', message: e.message || 'model request failed' }
    } else {
      status = 'failed'
      error = { code: 'UNKNOWN_TURN_END', message: 'turn ended without a known reason' }
    }

    let providerUsed
    let modelUsed
    try {
      const header = agent.session.requestHeader && agent.session.requestHeader()
      if (header && header.config) {
        providerUsed = header.config.provider
        modelUsed = header.config.model
      }
    } catch { /* ignore */ }

    const patch = {
      status,
      reply: outcome.reply,
      transcript: outcome.transcript,
      toolCalls: outcome.toolCalls,
      produced: outcome.produced,
      artifacts: await collectArtifacts(ctx.get('fs'), task.cwd, outcome.produced, cwdSnapshot),
      turnEnd: turnKind,
      error,
      provider: providerUsed || provider,
      model: modelUsed || model,
    }

    // Retention: release the live agent after a grace window so the session
    // stays inspectable in the Web UI; continuations cancel this timer.
    if (state.handles.get(task.sessionId) === handle) {
      const entry = state.handles.get(task.sessionId)
      entry.cleanup = timer.timeout(() => {
        if (state.handles.get(task.sessionId) !== handle) return
        state.handles.delete(task.sessionId)
        handle.dispose().catch(() => { /* agent already gone */ })
      }, cfg.retentionMs)
    }

    finish(patch)
  } catch (error) {
    finish({
      status: 'failed',
      error: { code: 'INTERNAL', message: error && error.message ? error.message : String(error) },
    })
  }
}

